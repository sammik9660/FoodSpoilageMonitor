"""Export the evaluated weak-label progression coefficients as one Apps Script data file."""
import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('model', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--edge-header', type=Path)
    args = parser.parse_args()
    model = json.loads(args.model.read_text(encoding='utf8'))
    if model['schema'] != 'assumed-progress-v1' or model['evaluation']['examples'] < 100:
        raise ValueError('Unexpected or insufficient model')
    args.output.write_text('// Generated by analysis/export_assumed_progress.py; weak endpoint assumptions only.\n'
                           'const FOOD_PROGRESS_MODEL_ = '
                           + json.dumps(model, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf8')
    if args.edge_header:
        selected = model['models']['model_time']
        def numbers(values):
            return ','.join(format(float(value), '.17g') for value in values)
        header = '''#pragma once
#include <cmath>
#include <cstring>
// Generated food/time fallback from the same weak-label model as FoodProgressModel.gs.
// Seven scalar features need no tensor arena or SIMD kernel.
namespace ai_progress {
constexpr const char* MODEL="assumed-progress-v1-time";
constexpr const char* FOODS[6]={"banana","chicken","egg","rice","sprouts","tofu"};
constexpr double MEAN[7]={''' + numbers(selected['mean']) + '''};
constexpr double SCALE[7]={''' + numbers(selected['scale']) + '''};
constexpr double WEIGHTS[7]={''' + numbers(selected['weights']) + '''};
constexpr double INTERCEPT=''' + format(selected['intercept'], '.17g') + ''';
struct Result {bool valid=false;int index=0;const char* stage="UNAVAILABLE";};
inline int foodIndex(const char* food){if(!food)return -1;for(int i=0;i<6;++i)
  if(!std::strcmp(food,FOODS[i]))return i;return -1;}
inline Result predict(int food,double elapsedHours){
  if(food<0||food>=6||!std::isfinite(elapsedHours)||elapsedHours<0)return {};
  double score=INTERCEPT;
  for(int i=0;i<6;++i){const double v=i==food?1.0:0.0;
    score+=WEIGHTS[i]*(v-MEAN[i])/SCALE[i];}
  score+=WEIGHTS[6]*(std::log1p(elapsedHours)-MEAN[6])/SCALE[6];
  const double bounded=score<-30?-30:score>30?30:score;
  const int index=int(std::round(100.0/(1.0+std::exp(-bounded))));
  return {true,index,index<33?"EARLY":index<67?"MIDDLE":"LATE"};
}
} // namespace ai_progress
'''
        args.edge_header.write_text(header, encoding='utf8')


if __name__ == '__main__':
    main()
